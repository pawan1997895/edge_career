"use client";

import * as React from "react";
import { Card, CardContent, CardDescription, CardHeader, CardTitle, CardAction } from "@/components/ui/card";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Tabs, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { CodeEditor } from "@/components/shared/code-editor";
import { CodeBlock } from "@/components/shared/rich-text";
import { LANGUAGE_LABELS, type CodeLanguage, type ProblemDetail } from "@/types/practice";

/** Signature (source of truth) and the boilerplate generated from it for each language. */
export function ProblemCodeTab({
  problem,
  signature,
  harnesses,
  referenceSolution,
  schemaSql,
}: {
  problem: ProblemDetail;
  signature: string;
  harnesses: Partial<Record<CodeLanguage, string>>;
  referenceSolution: string;
  schemaSql: string;
}) {
  const languages = Object.keys(harnesses) as CodeLanguage[];
  const [language, setLanguage] = React.useState<CodeLanguage>(languages[0] ?? "python");
  const [view, setView] = React.useState<"starter" | "harness">("starter");
  const isSql = problem.kind === "sql";

  const code = view === "starter" ? (problem.starterCode[language] ?? "") : (harnesses[language] ?? "");

  return (
    <div className="space-y-4">
      <Card>
        <CardHeader>
          <CardTitle>{isSql ? "Judge settings" : "Function signature"}</CardTitle>
          <CardDescription>
            {isSql
              ? "The query runs in a throwaway Postgres database and its rows are compared with the reference query's rows."
              : "Edit only this. Starter code and the judge harness for every language are generated from it."}
          </CardDescription>
        </CardHeader>
        <CardContent>
          <CodeBlock code={signature} />
        </CardContent>
      </Card>

      {isSql ? (
        <Card>
          <CardHeader>
            <CardTitle>Schema setup</CardTitle>
            <CardDescription>datasets/sample.sql. Hidden datasets reuse the same tables.</CardDescription>
          </CardHeader>
          <CardContent>
            <div className="h-72 overflow-hidden rounded-md border">
              <CodeEditor value={schemaSql} language="sql" readOnly />
            </div>
          </CardContent>
        </Card>
      ) : (
        <Card>
          <CardHeader>
            <CardTitle>Generated boilerplate</CardTitle>
            <CardDescription>Read-only preview. Regenerated by CI on every change.</CardDescription>
            <CardAction>
              <Select value={language} onValueChange={(v) => setLanguage(v as CodeLanguage)}>
                <SelectTrigger size="sm" className="w-44" aria-label="Language">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  {languages.map((l) => (
                    <SelectItem key={l} value={l}>
                      {LANGUAGE_LABELS[l]}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
            </CardAction>
          </CardHeader>
          <CardContent className="space-y-3">
            <Tabs value={view} onValueChange={(v) => setView(v as "starter" | "harness")}>
              <TabsList>
                <TabsTrigger value="starter">Starter code (learner sees)</TabsTrigger>
                <TabsTrigger value="harness">Judge harness</TabsTrigger>
              </TabsList>
            </Tabs>
            <div className="h-72 overflow-hidden rounded-md border">
              <CodeEditor value={code} language={language} readOnly />
            </div>
          </CardContent>
        </Card>
      )}

      <Card>
        <CardHeader>
          <CardTitle>Reference solution</CardTitle>
          <CardDescription>
            {isSql ? "reference/query.sql" : "reference/solution.py"} · expected outputs for every hidden test are generated by running it.
          </CardDescription>
        </CardHeader>
        <CardContent>
          <div className="h-72 overflow-hidden rounded-md border">
            <CodeEditor value={referenceSolution} language={isSql ? "sql" : "python"} />
          </div>
        </CardContent>
      </Card>
    </div>
  );
}
