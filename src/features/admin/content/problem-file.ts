export function referenceSolution(problem: ProblemDetail): string {
  if (REFERENCE_SOLUTIONS[problem.id]) return REFERENCE_SOLUTIONS[problem.id]!;
  if (problem.kind === "sql") return `-- reference/query.sql for ${problem.id}\n-- The expected output of every dataset is generated from this query.\nSELECT 1;\n`;
  return `# reference/solution.py for ${problem.id}\n# Every hidden test's expected output is generated by running this file.\nclass Solution:\n    ...\n`;
}

export function schemaSetupSql(problem: ProblemDetail): string {
  return (problem.schema ?? [])
    .map((table) => {
      const cols = table.columns.map((c) => `  ${c.name} ${c.type.toUpperCase()}`).join(",\n");
      const rows = table.rows
        .map((r) => `(${r.map((v) => (v === null ? "NULL" : typeof v === "number" ? v : `'${v}'`)).join(", ")})`)
        .join(",\n  ");
      return `CREATE TABLE ${table.name} (\n${cols}\n);\n\nINSERT INTO ${table.name} VALUES\n  ${rows};`;
    })
    .join("\n\n");
}
