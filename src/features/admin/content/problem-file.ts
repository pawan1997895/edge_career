// Builds the generated parts of a problem file for the editor preview: function signature,
// judge harness per language, reference solution and SQL schema setup. In the real
// pipeline these come from the content tooling; here they are derived from mock data.

import type { CodeLanguage, ProblemDetail } from "@/types/practice";

export interface Signature {
  functionName: string;
  params: { name: string; type: string }[];
  returns: string;
}

const PY_TYPE_MAP: Record<string, string> = {
  str: "string",
  int: "int",
  bool: "bool",
  float: "double",
  "list[int]": "int[]",
  "list[str]": "string[]",
  "list[list[int]]": "int[][]",
  "list[list[str]]": "string[][]",
};

/** Reads the signature from the Python starter code, which every code problem has. */
export function parseSignature(problem: ProblemDetail): Signature {
  const py = problem.starterCode.python ?? "";
  const match = py.match(/def (\w+)\(self,?\s*(.*?)\)\s*->\s*(.*?):/);
  if (!match) return { functionName: "solve", params: [{ name: "nums", type: "int[]" }], returns: "int" };
  const [, functionName, rawParams, rawReturn] = match;
  const params = rawParams!
    .split(",")
    .map((p) => p.trim())
    .filter(Boolean)
    .map((p) => {
      const [name, type = "any"] = p.split(":").map((s) => s.trim());
      return { name: name!, type: PY_TYPE_MAP[type] ?? type };
    });
  return { functionName: functionName!, params, returns: PY_TYPE_MAP[rawReturn!.trim()] ?? rawReturn!.trim() };
}

export function signatureYaml(problem: ProblemDetail, sig: Signature) {
  if (problem.kind === "sql") {
    return [
      `id: ${problem.id}`,
      "kind: sql",
      "engine: postgres16",
      "compare: unordered_rows",
      `tables: [${(problem.schema ?? []).map((t) => t.name).join(", ")}]`,
      `time_limit_ms: ${problem.timeLimitMs}`,
    ].join("\n");
  }
  return [
    `id: ${problem.id}`,
    "kind: function",
    `function: ${sig.functionName}`,
    "params:",
    ...sig.params.flatMap((p) => [`  - name: ${p.name}`, `    type: ${p.type}`]),
    `returns: ${sig.returns}`,
    `time_limit_ms: ${problem.timeLimitMs}`,
    `memory_limit_mb: ${problem.memoryLimitMb}`,
  ].join("\n");
}

const HEADER = "AUTO-GENERATED by content-tools from problem.yaml. Do not edit.";

export function judgeHarness(language: CodeLanguage, sig: Signature): string {
  const args = sig.params.map((p) => p.name);
  switch (language) {
    case "python":
      return `# ${HEADER}\nimport json, sys\nfrom solution import Solution\n\ndef main():\n    data = json.loads(sys.stdin.read())\n    result = Solution().${sig.functionName}(${args.map((a) => `data["${a}"]`).join(", ")})\n    print(json.dumps(result))\n\nif __name__ == "__main__":\n    main()\n`;
    case "java":
      return `// ${HEADER}\nimport com.edgecareer.judge.Json;\n\npublic class Main {\n    public static void main(String[] args) throws Exception {\n        var data = Json.readStdin();\n        var result = new Solution().${sig.functionName}(${args.map((a) => `data.get("${a}")`).join(", ")});\n        System.out.println(Json.write(result));\n    }\n}\n`;
    case "cpp":
      return `// ${HEADER}\n#include "judge/json.hpp"\n#include "solution.cpp"\n\nint main() {\n    auto data = judge::read_stdin();\n    Solution s;\n    auto result = s.${sig.functionName}(${args.map((a) => `data["${a}"]`).join(", ")});\n    judge::write_stdout(result);\n    return 0;\n}\n`;
    case "javascript":
      return `// ${HEADER}\nconst { ${sig.functionName} } = require("./solution");\n\nconst data = JSON.parse(require("fs").readFileSync(0, "utf8"));\nconst result = ${sig.functionName}(${args.map((a) => `data.${a}`).join(", ")});\nconsole.log(JSON.stringify(result));\n`;
    case "go":
      return `// ${HEADER}\npackage main\n\nimport (\n\t"encoding/json"\n\t"os"\n)\n\nfunc main() {\n\tvar data struct {\n${sig.params.map((p) => `\t\t${capitalize(p.name)} any \`json:"${p.name}"\``).join("\n")}\n\t}\n\tjson.NewDecoder(os.Stdin).Decode(&data)\n\tjson.NewEncoder(os.Stdout).Encode(${sig.functionName}(${sig.params.map((p) => `data.${capitalize(p.name)}`).join(", ")}))\n}\n`;
  }
}

function capitalize(s: string) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

