export interface InterviewSummary {
  id: string;
  type: InterviewType;
  mode: InterviewMode;
  title: string;
  company?: string;
  startedAt: string;
  durationMin: number;
  status: "completed" | "incomplete";
  /** Average of the assessed metrics, out of 5. Absent when not scored. */
  overallScore?: number;
  recommendation?: Recommendation;
  /** Shown for sessions that were not scored. */
  note?: string;
}

export interface TranscriptTurn {
  id: string;
  speaker: "interviewer" | "candidate";
  text: string;
  atSec: number;
  stage: InterviewStage;
}

export interface MetricEvidence {
  turnId: string;
  quote: string;
}

export interface ScorecardMetric {
  key: MetricKey;
  /** Out of 5. `null` when the metric is not assessed for this interview type. */
  score: number | null;
  summary: string;
  evidence: MetricEvidence[];
  tips: string[];
}

export interface StageTiming {
  stage: InterviewStage;
  actualMin: number;
}

export interface Scorecard extends InterviewSummary {
  summary: string;
  metrics: ScorecardMetric[];
  stageTimings: StageTiming[];
  transcript: TranscriptTurn[];
  /** Final code for coding rounds, or design notes for HLD and behavioral rounds. */
  finalArtifact?: { kind: "code"; language: CodeLanguage; content: string } | { kind: "notes"; content: string };
  practiseNext: { title: string; href: string; reason: string }[];
}

/** One scripted turn in a mock live session. The real interviewer is generated by Claude. */
export interface ScriptedTurn {
  speaker: "interviewer" | "candidate";
  text: string;
  stage: InterviewStage;
  /** Simulated time from the candidate finishing to the interviewer starting to speak. */
  latencyMs?: number;
}

export interface LiveSession {
  id: string;
  type: InterviewType;
  mode: InterviewMode;
  title: string;
  company?: string;
  durationMin: number;
  problem: {
    title: string;
    statement: string[];
    examples: { input: string; output: string; explanation?: string }[];
    constraints: string[];
  };
  starterCode: Partial<Record<CodeLanguage, string>>;
  /**
   * Voice and avatar sessions play the whole script. Text sessions post the interviewer
   * turns and offer the candidate turns as sample replies.
   */
  script: ScriptedTurn[];
}

export interface InterviewQuota {
  plan: PlanId;
  minutesLeft: number;
  minutesTotal: number;
  minutesUsed: number;
  resetsAt: string;
  planCaps: { plan: PlanId; minutes: number; period: string }[];
}
